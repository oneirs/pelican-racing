import test from "node:test";
import assert from "node:assert/strict";
import { bindRiding } from "../src/controls/riding.js";

test("S reverses, Space jumps once per press, and pause/blur discard jump input", () => {
  const saved = { addEventListener: globalThis.addEventListener, document: globalThis.document };
  const handlers = new Map();
  globalThis.addEventListener = (name, fn) => handlers.set(name, fn);
  const element = { addEventListener() {}, setPointerCapture() {} };
  globalThis.document = { getElementById: () => element, addEventListener() {} };
  const state = { screen: "race", running: true, steerVisual: 0, targetKmh: 500, grounded: true };
  const key = (code, repeat = false) => handlers.get("keydown")({ code, repeat, target: { tagName: "CANVAS" }, preventDefault() {} });
  try {
    const update = bindRiding(element, state, () => { state.running = !state.running; });
    key("KeyE"); update(1 / 60); assert(state.gatlingHeld);
    handlers.get("keyup")({code:"KeyE"}); update(1 / 60); assert(!state.gatlingHeld);
    key("KeyE"); handlers.get("blur")(); update(1 / 60); assert(!state.gatlingHeld);
    key("KeyS"); update(1 / 60);
    assert.equal(state.throttleInput, -1);
    assert(!state.brakeInput);
    handlers.get("keyup")({ code: "KeyS" }); update(1 / 60);
    assert.equal(state.throttleInput, 0);
    key("ArrowDown"); update(1 / 60);
    assert.equal(state.throttleInput, -1);
    handlers.get("keyup")({ code: "ArrowDown" }); update(1 / 60);
    key("KeyW"); update(1 / 60);
    assert.equal(state.throttleInput, 1);
    handlers.get("keyup")({ code: "KeyW" }); update(1 / 60);
    assert.equal(state.throttleInput, 0, "released accelerator stayed engaged");
    assert.equal(state.targetKmh, 500, "throttle changed the configured speed limit");
    key("ShiftLeft"); key("ArrowUp"); key("ArrowRight"); update(1 / 60);
    assert.equal(state.balancePitch, 1);
    assert.equal(state.balanceRoll, 1);
    assert.equal(state.throttleInput, 0, "weight-only input accelerated");
    assert.equal(state.steerInput, 0, "weight-only input steered");
    key("KeyW"); key("KeyA"); update(1 / 60);
    assert.equal(state.throttleInput, 1);
    assert.equal(state.steerInput, -1);
    for (const code of ["ShiftLeft", "ArrowUp", "ArrowRight", "KeyW", "KeyA"]) handlers.get("keyup")({ code });
    key("ArrowDown"); update(1 / 60);
    assert.equal(state.balancePitch, -1, "ground reverse did not shift weight back");
    assert.equal(state.throttleInput, -1);
    handlers.get("keyup")({ code: "ArrowDown" });
    state.crashed = true; state.grounded = false;
    key("KeyW"); update(1 / 60); assert(state.balanceAssistHeld); assert.equal(state.throttleInput,1);
    handlers.get("keyup")({code:"KeyW"}); update(1 / 60); assert(!state.balanceAssistHeld);
    key("ArrowRight"); key("ArrowUp"); update(1 / 60);
    assert.equal(state.balanceRoll, 1);
    assert.equal(state.balancePitch, 1);
    assert.equal(state.throttleInput, 0);
    handlers.get("keyup")({ code: "ArrowRight" }); handlers.get("keyup")({ code: "ArrowUp" });
    state.crashed = false; state.grounded = true;
    key("Space"); update(1 / 60);
    assert(state.jumpRequested);
    assert(!state.brakeInput, "Space still applied the brakes");
    state.jumpRequested = false;
    key("Space", true); update(1 / 60);
    assert(!state.jumpRequested, "held Space repeated a jump");
    handlers.get("keyup")({ code: "Space" }); key("Space");
    assert(state.jumpRequested);
    handlers.get("blur")();
    assert(!state.jumpRequested);
    key("KeyE"); key("Space"); key("KeyP"); update(1 / 60);
    assert(!state.jumpRequested, "paused input queued a jump");
    assert(!state.gatlingHeld); assert(!state.balanceAssistHeld);
  } finally {
    for (const [k, v] of Object.entries(saved)) v === undefined ? delete globalThis[k] : globalThis[k] = v;
  }
});
